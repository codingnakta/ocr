"""File storage abstraction: local directory (dev) or S3-compatible object storage.

Keys are always generated by the server (never from user-supplied names), and the
local backend additionally refuses any key that would escape the storage root.
Files are never exposed via public URLs; downloads stream through authenticated
API routes.
"""

from __future__ import annotations

import os
import re
import shutil
import tempfile
from collections.abc import Iterator
from contextlib import contextmanager
from functools import lru_cache
from pathlib import Path

from app.core.config import get_settings

_KEY_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._/-]{0,390}$")


def _check_key(key: str) -> str:
    if not _KEY_RE.match(key) or ".." in key.split("/"):
        raise ValueError(f"invalid storage key: {key!r}")
    return key


class Storage:
    def put_bytes(self, key: str, data: bytes, content_type: str | None = None) -> None: ...
    def put_file(self, key: str, path: Path, content_type: str | None = None) -> None: ...
    def get_bytes(self, key: str) -> bytes: ...
    def exists(self, key: str) -> bool: ...
    def size(self, key: str) -> int: ...
    def delete(self, key: str) -> None: ...
    def delete_prefix(self, prefix: str) -> None: ...

    @contextmanager
    def local_path(self, key: str) -> Iterator[Path]:  # pragma: no cover - interface
        yield Path()

    def iter_chunks(self, key: str, chunk_size: int = 1 << 20) -> Iterator[bytes]:  # pragma: no cover
        yield self.get_bytes(key)


class LocalStorage(Storage):
    def __init__(self, root: Path):
        self.root = root.resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        p = (self.root / _check_key(key)).resolve()
        if self.root not in p.parents:
            raise ValueError("storage key escapes root")
        return p

    def put_bytes(self, key, data, content_type=None):
        p = self._path(key)
        p.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=p.parent, prefix=".tmp-")
        with os.fdopen(fd, "wb") as f:
            f.write(data)
        os.replace(tmp, p)  # atomic: readers never see partial files

    def put_file(self, key, path, content_type=None):
        p = self._path(key)
        p.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=p.parent, prefix=".tmp-")
        os.close(fd)
        shutil.copyfile(path, tmp)
        os.replace(tmp, p)

    def get_bytes(self, key):
        return self._path(key).read_bytes()

    def exists(self, key):
        return self._path(key).is_file()

    def size(self, key):
        return self._path(key).stat().st_size

    def delete(self, key):
        try:
            self._path(key).unlink()
        except FileNotFoundError:
            pass

    def delete_prefix(self, prefix):
        p = self._path(prefix.rstrip("/"))
        if p.is_dir():
            shutil.rmtree(p, ignore_errors=True)

    @contextmanager
    def local_path(self, key):
        yield self._path(key)

    def iter_chunks(self, key, chunk_size=1 << 20):
        with open(self._path(key), "rb") as f:
            while chunk := f.read(chunk_size):
                yield chunk


class S3Storage(Storage):  # pragma: no cover - exercised only with a real bucket
    def __init__(self, bucket: str, prefix: str, endpoint_url: str | None, region: str | None):
        import boto3

        self.bucket = bucket
        self.prefix = prefix
        self.client = boto3.client("s3", endpoint_url=endpoint_url, region_name=region)

    def _k(self, key: str) -> str:
        return self.prefix + _check_key(key)

    def put_bytes(self, key, data, content_type=None):
        extra = {"ContentType": content_type} if content_type else {}
        self.client.put_object(Bucket=self.bucket, Key=self._k(key), Body=data, **extra)

    def put_file(self, key, path, content_type=None):
        extra = {"ExtraArgs": {"ContentType": content_type}} if content_type else {}
        self.client.upload_file(str(path), self.bucket, self._k(key), **extra)

    def get_bytes(self, key):
        return self.client.get_object(Bucket=self.bucket, Key=self._k(key))["Body"].read()

    def exists(self, key):
        try:
            self.client.head_object(Bucket=self.bucket, Key=self._k(key))
            return True
        except Exception:
            return False

    def size(self, key):
        return int(self.client.head_object(Bucket=self.bucket, Key=self._k(key))["ContentLength"])

    def delete(self, key):
        self.client.delete_object(Bucket=self.bucket, Key=self._k(key))

    def delete_prefix(self, prefix):
        paginator = self.client.get_paginator("list_objects_v2")
        for page in paginator.paginate(Bucket=self.bucket, Prefix=self._k(prefix)):
            objs = [{"Key": o["Key"]} for o in page.get("Contents", [])]
            if objs:
                self.client.delete_objects(Bucket=self.bucket, Delete={"Objects": objs})

    @contextmanager
    def local_path(self, key):
        work = get_settings().work_dir
        work.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=work, suffix=Path(key).suffix)
        os.close(fd)
        try:
            self.client.download_file(self.bucket, self._k(key), tmp)
            yield Path(tmp)
        finally:
            Path(tmp).unlink(missing_ok=True)

    def iter_chunks(self, key, chunk_size=1 << 20):
        body = self.client.get_object(Bucket=self.bucket, Key=self._k(key))["Body"]
        yield from body.iter_chunks(chunk_size)


@lru_cache
def get_storage() -> Storage:
    s = get_settings()
    if s.storage_backend == "s3":
        if not s.s3_bucket:
            raise RuntimeError("S3_BUCKET is required when STORAGE_BACKEND=s3")
        return S3Storage(s.s3_bucket, s.s3_prefix, s.s3_endpoint_url, s.s3_region)
    return LocalStorage(s.storage_dir)


def doc_prefix(document_id: str) -> str:
    return f"docs/{document_id}/"
